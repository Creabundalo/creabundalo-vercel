const fs=require('fs');
const vm=require('vm');
const {webcrypto,createHash}=require('crypto');
if(!globalThis.crypto?.subtle) globalThis.crypto=webcrypto;
globalThis.__m99fs=fs;

const files=[
  'm24-core.js','m24-cases.js','m24-lab.js','m24-primary-lab.js','m24-coinbase.js',
  'm24-meaning.js','m24-derivatives.js','m24-derivatives-lab.js',
  'm24-binance-vision.js','m24-funding-archive.js','m24-binance-vision-lab.js',
  'm24-macro.js','m24-macro-lab.js','m24-backtest.js','m24-evidence-gate.js','m24-enrichment.js'
];
const source=files.map(f=>fs.readFileSync(f,'utf8')).join('\n');
const test=`
(async()=>{
  const caseIds=['SOL-2021-2022-TOP-MARKDOWN','BTC-2019-TOP-MARKDOWN'];
  const providers=()=>({
    price:new M24Coinbase.CoinbaseHistoricalProvider(),
    derivatives:new M24FundingArchive.BinanceHistoricalDerivativesProvider(),
    archive:new M24BinanceVision.BinanceVisionMetricsProvider(),
    macro:new M24Macro.FredCsvProvider()
  });
  const batch={
    type:'M99_BATCH_CHECKPOINT',
    batchId:'M99-B002',
    phase:'FILL',
    startedAt:new Date().toISOString(),
    cases:[],
    summary:{done:0,incomplete:0,blocked:0,sourceGaps:0},
    rule:'Continue after individual incomplete/blocked cases; preserve source gaps and report one checkpoint.'
  };

  for(const caseId of caseIds){
    const caseSchema=M24Cases.get(caseId);
    const entry={caseId,asset:caseSchema?.asset||null,status:'RUNNING',startedAt:new Date().toISOString()};
    try{
      const store=new M24Core.QubusStore();
      const result=await M24Enrichment.runCase({store,caseSchema,providers:providers(),granularity:86400});
      const gaps=store.list('SOURCE_GAP').map(r=>r.data);
      entry.status=result.calibrationEligible?'DONE':'INCOMPLETE';
      entry.state=result.state;
      entry.calibrationEligible=result.calibrationEligible;
      entry.coverageProfile=result.evidence?.coverageProfile||null;
      entry.missingLayers=result.evidence?.missingLayers||[];
      entry.resolvedCheckpoints={
        firstTop:result.backtest?.snapshot?.price?.firstTop?.date||null,
        secondTop:result.backtest?.snapshot?.price?.secondTop?.date||null,
        decisionAsOf:result.backtest?.snapshot?.asOf||null,
        supportBreakDate:result.backtest?.outcome?.supportBreakDate||null,
        troughDate:result.backtest?.outcome?.troughDate||null
      };
      entry.actionCandidate=result.backtest?.candidate?{
        action:result.backtest.candidate.action,
        score:result.backtest.candidate.score,
        coverage:result.backtest.candidate.coverage
      }:null;
      entry.meaningScope=result.meaning?.sourceScope||null;
      entry.sourceGaps=gaps;
      entry.layers=Object.fromEntries(Object.entries(result.evidence?.layers||{}).map(([k,v])=>[k,{state:v.state,note:v.note,extensionState:v.extensionState||null}]));
      entry.recordsByType=Object.fromEntries([...new Set(store.records.map(r=>r.type))].sort().map(type=>[type,store.list(type).length]));
      batch.summary.sourceGaps+=gaps.length;
      if(entry.status==='DONE') batch.summary.done+=1; else batch.summary.incomplete+=1;

      if(result.calibrationEligible){
        const snapshot={
          type:'VERIFIED_SOURCE_SNAPSHOT',caseId,asset:caseSchema.asset,coverageProfile:result.evidence.coverageProfile,
          verification:{workflow:'M99-B002 Crypto Batch',workflowRunId:null,artifactId:null,artifactDigest:null,headSha:null,verifiedAt:new Date().toISOString(),sourceComplete:true},
          state:'SOURCE_COMPLETE',calibrationEligible:true,resolvedCheckpoints:entry.resolvedCheckpoints,
          evidenceLayers:Object.fromEntries(Object.entries(result.evidence.layers).map(([k,v])=>[k,{state:v.state,note:v.note,extensionState:v.extensionState||null}])),
          sourceGaps:gaps,actionCandidate:result.backtest.candidate,
          note:'Generated by M99-B002 batch source run. Artifact/run identifiers are attached after CI checkpoint verification.'
        };
        const name='m99-'+caseSchema.asset.toLowerCase()+'-'+caseId.toLowerCase().replace(/[^a-z0-9]+/g,'-')+'-source-snapshot.json';
        globalThis.__m99fs.writeFileSync(name,JSON.stringify(snapshot,null,2));
        entry.snapshotFile=name;
      }
    }catch(err){
      entry.status='BLOCKED';
      entry.error={message:String(err?.message||err),code:err?.code||null};
      batch.summary.blocked+=1;
    }
    entry.finishedAt=new Date().toISOString();
    batch.cases.push(entry);
  }

  batch.finishedAt=new Date().toISOString();
  globalThis.__m99fs.writeFileSync('m99-b002-crypto-checkpoint.json',JSON.stringify(batch,null,2));
  console.log('M99 B002 crypto batch checkpoint');
  console.log(JSON.stringify(batch));
})().catch(err=>{console.error(err);process.exit(1)});
`;
vm.runInThisContext(`${source}\n${test}`,{filename:'m99-b002-crypto-batch-bundle.js'});
